namespace Wander.Core.Icons;

public enum IconSize {
    Small,   // ~16px
    Normal,  // ~32px

    /// <summary>
    /// ~96px, и это <b>миниатюра</b>, а не значок: для файла с превью
    /// (картинка, RAW, видео, PDF) вернётся содержимое файла, для папки —
    /// win11-заглядывание внутрь. Для остальных — обычный значок по
    /// расширению, как у <see cref="Normal"/>.
    ///
    /// Отдельная ступень между Normal и Large нужна плиточному режиму:
    /// значок там 32–64px, тянуть ради него 256px-миниатюру — это вчетверо
    /// больше декодирования и памяти на каждую плитку.
    /// </summary>
    Medium,

    Large,   // jumbo, до 256px
}
